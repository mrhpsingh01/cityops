"use client";

import { useState } from 'react';
import * as Dialog from '@radix-ui/react-dialog';
import { PaperPlaneTiltIcon, CheckCircleIcon, CopyIcon, CheckIcon, WarningCircleIcon } from '@phosphor-icons/react';
import { HotspotCluster, DispatchAlertResult, dispatchAlert } from '@/lib/api';

interface DispatchAlertModalProps {
  cluster: HotspotCluster | null;
  open: boolean;
  onOpenChange: (open: boolean) => void;
}

export function DispatchAlertModal({ cluster, open, onOpenChange }: DispatchAlertModalProps) {
  const [loading, setLoading] = useState(false);
  const [result, setResult] = useState<DispatchAlertResult | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [copied, setCopied] = useState(false);

  if (!cluster) return null;

  const jsonString = result?.payloadPreview ?? '';

  const handleDispatch = async () => {
    setLoading(true);
    setError(null);
    try {
      const res = await dispatchAlert(cluster.clusterId);
      setResult(res);
    } catch (err: unknown) {
      setError(String(err));
    } finally {
      setLoading(false);
    }
  };

  const copyPayload = () => {
    if (!jsonString) return;
    navigator.clipboard.writeText(jsonString);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <Dialog.Root open={open} onOpenChange={(v) => { onOpenChange(v); if (!v) { setResult(null); setError(null); } }}>
      <Dialog.Portal>
        <Dialog.Overlay className="dialog-overlay" />
        <Dialog.Content className="dialog-content max-w-2xl" aria-describedby="dispatch-desc">
          <div className="flex items-center justify-between pb-3 border-b border-[var(--border)]">
            <div className="flex items-center gap-2">
              <span className={`p-2 rounded-md ${cluster.severityTier === 'CRITICAL' ? 'bg-rose-500/10 text-rose-400' : 'bg-amber-500/10 text-amber-400'}`}>
                <PaperPlaneTiltIcon size={22} weight="fill" />
              </span>
              <div>
                <Dialog.Title className="text-base font-semibold text-[var(--foreground)]">
                  Dispatch Outage Triage Alert
                </Dialog.Title>
                <p id="dispatch-desc" className="text-xs text-[var(--muted)]">
                  Webhook Dispatcher (Slack / PagerDuty) with Automated Audit Logging
                </p>
              </div>
            </div>
            <Dialog.Close className="drawer-close" aria-label="Close">✕</Dialog.Close>
          </div>

          <div className="py-4 space-y-4 text-xs text-[var(--foreground)]">
            <div className="p-3 rounded-lg bg-[var(--surface-sunken)] border border-[var(--border)] space-y-1.5">
              <div className="flex items-center justify-between">
                <span className="font-semibold text-[var(--foreground)]">{cluster.clusterId}</span>
                <span className={`px-2 py-0.5 rounded text-[10px] font-bold ${cluster.severityTier === 'CRITICAL' ? 'bg-rose-500/20 text-rose-400' : 'bg-amber-500/20 text-amber-400'}`}>
                  {cluster.severityTier}
                </span>
              </div>
              <p className="text-[var(--muted)] leading-relaxed">{cluster.triageHypothesis}</p>
              <div className="flex items-center gap-4 text-[11px] text-[var(--muted)] pt-1">
                <span>Incidents: <strong className="text-[var(--foreground)]">{cluster.incidentCount}</strong></span>
                <span>Radius: <strong className="text-[var(--foreground)]">{Math.round(cluster.radiusMeters)}m</strong></span>
                <span>Est. TTC: <strong className="text-emerald-400">{cluster.predictedTtcHours} hrs</strong></span>
              </div>
            </div>

            <div>
              <div className="flex items-center justify-between mb-1.5">
                <span className="text-[11px] font-semibold uppercase tracking-wider text-[var(--muted)]">
                  Webhook JSON payload returned by the API:
                </span>
                <button
                  type="button"
                  onClick={copyPayload}
                  className="flex items-center gap-1 text-[11px] text-[var(--muted)] hover:text-[var(--foreground)]"
                >
                  {copied ? <CheckIcon size={12} className="text-emerald-400" /> : <CopyIcon size={12} />}
                  <span>{copied ? 'Copied' : 'Copy JSON'}</span>
                </button>
              </div>
              <pre className="p-3 rounded-lg bg-[var(--surface-sunken)] border border-[var(--border)] text-[11px] font-mono text-emerald-300 max-h-48 overflow-y-auto" data-testid="dispatch-payload">
                {jsonString || 'Payload is generated by the API when you dispatch (POST /api/v1/hotspots/:clusterId/dispatch-alert).'}
              </pre>
            </div>

            {result && (
              <div className="p-3 rounded-lg bg-emerald-500/10 border border-emerald-500/30 space-y-2">
                <div className="flex items-center gap-1.5 font-semibold text-emerald-400 text-xs">
                  <CheckCircleIcon size={16} weight="fill" />
                  <span>Webhook Receipt: {result.status.toUpperCase()} (HTTP {result.responseStatus})</span>
                </div>
                <div className="text-[11px] text-[var(--foreground)] space-y-0.5 font-mono">
                  <div>Audit ID: {result.dispatchId}</div>
                  <div>Channel: {result.channel} ({result.destinationUrl ?? 'simulated dry-run'})</div>
                  <div>Dispatched At: {result.dispatchedAt}</div>
                  <div className="text-emerald-300 pt-1">{result.message}</div>
                </div>
              </div>
            )}

            {error && (
              <div className="p-3 rounded-lg bg-rose-500/10 border border-rose-500/30 text-rose-400 text-xs flex items-center gap-2">
                <WarningCircleIcon size={16} />
                <span>{error}</span>
              </div>
            )}
          </div>

          <div className="flex items-center justify-between pt-3 border-t border-[var(--border)]">
            <span className="text-[11px] text-[var(--muted)]">
              No webhook configured? The API performs a dry run and returns a 200 receipt.
            </span>
            <div className="flex items-center gap-2">
              <button
                type="button"
                onClick={() => onOpenChange(false)}
                className="px-3 py-1.5 text-xs font-medium rounded-md bg-[var(--surface-sunken)] hover:bg-[var(--surface-raised)] border border-[var(--border)] text-[var(--foreground)]"
              >
                Cancel
              </button>
              <button
                type="button"
                disabled={loading}
                onClick={handleDispatch}
                className="px-4 py-1.5 text-xs font-semibold rounded-md bg-rose-600 hover:bg-rose-500 text-white flex items-center gap-1.5 shadow-sm disabled:opacity-50"
              >
                <PaperPlaneTiltIcon size={14} weight="fill" />
                <span>{loading ? 'Dispatching…' : result ? 'Dispatch Again' : 'Dispatch Webhook Alert'}</span>
              </button>
            </div>
          </div>
        </Dialog.Content>
      </Dialog.Portal>
    </Dialog.Root>
  );
}
